#!/usr/bin/env python3
"""Compare two rendered images pixel by pixel and write a diff image and a JSON receipt.

Either input may be a PNG/JPEG/TIFF or a PDF (first page, or ``--page``). PDFs are
rasterised with PyMuPDF at ``--dpi`` (default 300). Raster inputs are compared as they
are; if their sizes differ the check fails and no resampling is done, because resampling
would hide differences.

A pixel differs when any RGB channel differs by more than ``--tolerance`` (0-255,
default 0). The receipt records both inputs' sha256, the dpi, image sizes, the number
and fraction of differing pixels, the maximum channel difference and the bounding box of
the differences.

Usage
-----
    python tools/check_pixels.py NEW EXPECTED --out figures/Fig2/checks/panel_b
        [--dpi 300] [--page 0] [--tolerance 0] [--max-fraction 0]

writes ``<out>.diff.png`` (differing pixels in red over a faded EXPECTED) and
``<out>.json``. Exit 0 when the differing fraction is <= ``--max-fraction``.
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

REPO = Path(__file__).resolve().parents[1]

#: Default rasterisation resolution for PDFs (dots per inch); the journal print standard.
DEFAULT_DPI = 300


def sha256(path):
    """Return the hex sha256 of a file."""
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def load_rgb(path, dpi=DEFAULT_DPI, page=0):
    """Load an image or one PDF page as an RGB uint8 array.

    Parameters
    ----------
    path : pathlib.Path
        PNG/JPEG/TIFF or PDF.
    dpi : int
        Rasterisation resolution for PDFs.
    page : int
        Zero-based PDF page.

    Returns
    -------
    numpy.ndarray
        Array of shape (height, width, 3), dtype uint8. Transparent pixels are composited
        on white.
    """
    if path.suffix.lower() == ".pdf":
        import fitz  # PyMuPDF

        with fitz.open(path) as doc:
            pix = doc[page].get_pixmap(dpi=dpi, alpha=False, colorspace=fitz.csRGB)
            return np.frombuffer(pix.samples, dtype=np.uint8).reshape(pix.height, pix.width, 3).copy()
    im = Image.open(path)
    if im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGBA")
        bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
        im = Image.alpha_composite(bg, im)
    return np.asarray(im.convert("RGB"))


def rel(path):
    """Return ``path`` relative to the repository when inside it, else its file name."""
    try:
        return Path(path).resolve().relative_to(REPO).as_posix()
    except ValueError:
        return Path(path).name


def compare(new, expected, out, dpi=DEFAULT_DPI, page=0, tolerance=0, max_fraction=0.0):
    """Compare two images and write ``<out>.diff.png`` and ``<out>.json``.

    Parameters
    ----------
    new, expected : str or pathlib.Path
        Image regenerated by the notebook, and reference image from the original producer.
    out : str or pathlib.Path
        Output stem.
    dpi, page : int
        PDF rasterisation settings.
    tolerance : int
        Per-channel difference (0-255) at or below which a pixel counts as equal.
    max_fraction : float
        Largest fraction of differing pixels that still passes.

    Returns
    -------
    dict
        The receipt that was written.
    """
    new, expected, out = Path(new), Path(expected), Path(out)
    a, b = load_rgb(new, dpi, page), load_rgb(expected, dpi, page)
    receipt = {
        "new": rel(new), "new_sha256": sha256(new),
        "expected": rel(expected), "expected_sha256": sha256(expected),
        "dpi": dpi, "page": page, "tolerance": tolerance, "max_fraction": max_fraction,
        "new_size_px": [a.shape[1], a.shape[0]], "expected_size_px": [b.shape[1], b.shape[0]],
    }
    out.parent.mkdir(parents=True, exist_ok=True)
    if a.shape != b.shape:
        receipt.update(verdict="SIZE_MISMATCH", passed=False)
    else:
        delta = np.abs(a.astype(np.int16) - b.astype(np.int16)).max(axis=2)
        mask = delta > tolerance
        n = int(mask.sum())
        frac = n / mask.size
        ys, xs = np.nonzero(mask)
        receipt.update(
            differing_pixels=n,
            differing_fraction=frac,
            max_channel_difference=int(delta.max()),
            diff_bbox_px=[int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max())] if n else None,
            verdict="IDENTICAL" if n == 0 else "DIFFERENT",
            passed=frac <= max_fraction,
        )
        faded = (255 - (255 - b.astype(np.float32)) * 0.25).astype(np.uint8)
        faded[mask] = [220, 0, 0]
        diff_path = out.with_name(out.name + ".diff.png")
        Image.fromarray(faded).save(diff_path)
        receipt["diff_png"] = rel(diff_path)
    json_path = out.with_name(out.name + ".json")
    json_path.write_text(json.dumps(receipt, indent=1) + "\n")
    return receipt


def main(argv=None):
    """Command-line entry point."""
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("new")
    ap.add_argument("expected")
    ap.add_argument("--out", required=True, help="output stem for .diff.png and .json")
    ap.add_argument("--dpi", type=int, default=DEFAULT_DPI)
    ap.add_argument("--page", type=int, default=0)
    ap.add_argument("--tolerance", type=int, default=0)
    ap.add_argument("--max-fraction", type=float, default=0.0)
    a = ap.parse_args(argv)
    r = compare(a.new, a.expected, a.out, a.dpi, a.page, a.tolerance, a.max_fraction)
    print(json.dumps({k: r.get(k) for k in ("verdict", "differing_pixels", "differing_fraction", "passed")}))
    return 0 if r["passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
